const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.resolve(process.argv[2] || 'artifacts/demo/heat_loss_viewer.html')).href);
 await page.waitForFunction(()=>document.getElementById('load-state').hidden);
 await page.locator('#room-list tr').first().click();
 assert.notEqual(await page.locator('#card-loss').textContent(),'демо');
 const theme=await page.locator('html').getAttribute('data-theme');
 await page.locator('#btn-theme').click();
 assert.notEqual(await page.locator('html').getAttribute('data-theme'),theme);
 await page.locator('#btn-theme').click();
 const initial=await page.locator('#total-loss').textContent();
 await page.locator('[data-view="inputs"]').click();
 await page.locator('#input-outdoor').fill('-40');
 await page.locator('#calc-form button[type=submit]').click();
 assert.notEqual(await page.locator('#total-loss').textContent(),initial);
 await page.locator('#inputs-reviewed').check();await page.locator('#calc-form button[type=submit]').click();
 assert.match(await page.locator('#calc-state').textContent(),/^Бета/);
 const downloadEvent=page.waitForEvent('download');await page.locator('#export-results').click();
 const download=await downloadEvent;assert.equal(download.suggestedFilename(),'heat_loss_results.json');
 await page.locator('[data-view="totals"]').click();
 assert.ok(await page.locator('#floor-totals tr').count()>0);
 await page.locator('[data-view="model"]').click();
 await page.locator('#show-openings').uncheck();await page.locator('#show-openings').check();
 await page.locator('#show-shell').check();await page.locator('#show-shell').uncheck();
 await page.locator('[data-mode="specificArea"]').click();
 await page.locator('#btn-theme').click();
 await page.waitForTimeout(300);await page.screenshot({path:'artifacts/dashboard-dark.png',fullPage:true});
 await page.locator('#btn-theme').click();
 await page.waitForTimeout(300);await page.screenshot({path:'artifacts/dashboard-light.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS dark/light themes, thermal recalculation, inputs, result download, totals, openings, opacity, thermal colors, mobile');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
