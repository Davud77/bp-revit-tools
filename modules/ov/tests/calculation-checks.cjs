const assert=require('node:assert/strict');
const fs=require('node:fs');
for(const file of ['Poteri.js','Calculation.js'])require('node:vm').runInThisContext(fs.readFileSync('HeatLossViewer/Viewer/'+file,'utf8'));
const engine=globalThis.HeatLossEngine;
const room={key:'r1',area:20,volume:60,height:3,surfaces:[{key:'s1',hostKey:'wall1',kind:'wall',exposure:'outside',grossArea:20}]};
const openings=[{key:'w1',hostKey:'wall1',kind:'window',roomKeys:['r1'],area:2,position:[1,0,1.5],height:1.2}];
const input={...engine.defaults,indoor:20,outdoor:-20,windowGn:0,wall:.3,window:1.2};
let result=engine.calculate(room,openings,input);
assert.ok(Math.abs(result.transmission-(18*.3+2*1.2)*40)<1e-9);
assert.equal(result.air,0);
assert.ok(Math.abs(result.total-312)<1e-9);
assert.equal(result.status,'demo');
// A split wall must subtract and count the window only once.
const split={...room,surfaces:[{...room.surfaces[0],grossArea:8},{...room.surfaces[0],key:'s2',grossArea:12}]};
assert.equal(engine.calculate(split,openings,input).total,result.total);
assert.equal(engine.calculate({...room,surfaces:[]},openings,input).total,null);
assert.equal(engine.calculate({...room,surfaces:[{...room.surfaces[0],exposure:'unknown'}]},openings,input).total,null);
assert.equal(engine.calculate(room,openings,{...input,method:'simple',airMode:'airChanges',airChanges:100}).total,result.total);
assert.equal(engine.calculate(room,openings,{...input,indoor:-30}).total,0);
assert.equal(engine.calculate({...room,volume:0},openings,input).air,0);
assert.equal(engine.calculate(room,openings,{...input,reviewed:true}).status,'beta');
assert.equal(engine.calculate(room,openings,input,{s1:{exposure:'inside'}}).transmission,0);
assert.equal(engine.calculate(room,openings,{...input,roomOverrides:{r1:{indoor:10}}}).air,0);
const excessive=[{...openings[0],area:21}];
assert.equal(engine.calculate(room,excessive,input).total,null);
assert.equal(engine.calculate(room,openings,input,{s1:{u:-.5}}).total,null);
const exact={...room,surfaces:[{...room.surfaces[0],netArea:17,cuts:[{key:'c1',kind:'window',openingKey:'w1',area:3}]}]};
assert.equal(engine.calculate(exact,openings,input).transmission,(17*.3+3*1.2)*40);
assert.equal(engine.calculate({...exact,surfaces:[{...exact.surfaces[0],cuts:[{key:'c1',kind:'cut',area:3}]}]},openings,input).total,null);
assert.equal(engine.calculate({...exact,surfaces:[{...exact.surfaces[0],cuts:[{key:'c1',kind:'cut',area:3}]}]},openings,input,{c1:{u:1.2}}).transmission,(17*.3+3*1.2)*40);
console.log('PASS SI formulas, net areas, opening deduplication, incomplete rooms, input validation, overrides, demo/beta provenance');
